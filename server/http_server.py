#!/usr/bin/env python3
"""PS Linker HTTP share for the PSP/PS3 NASDL apps.

A small stdlib-only file server that serves the games library over HTTP
with support for:

- ``Range`` requests (``bytes=start-end``), so interrupted client
  downloads can resume from where they left off instead of restarting.
- Correct ``Content-Length`` and ``Accept-Ranges`` headers.
- Directory listings in the same simple HTML format the stock
  ``python3 -m http.server`` produces, so the existing client-side
  directory parsers keep working unchanged.
- ``/catalog.json`` passthrough (it is generated by the Store loop).

Usage: http_server.py <games_dir> [port]
"""
import html
import os
import re
import sys
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import unquote, urlparse

RANGE_RE = re.compile(r"^bytes=(\d*)-(\d*)$")


def make_handler(games_dir: str):
    class PSLinkerHandler(BaseHTTPRequestHandler):
        server_version = "PSLinker/1.1"

        def do_GET(self):
            path = unquote(urlparse(self.path).path)
            # Resolve inside games_dir only (no traversal).
            fs_path = os.path.realpath(os.path.join(games_dir, path.lstrip("/")))
            if not (fs_path == games_dir or fs_path.startswith(games_dir + os.sep)):
                self.send_error(403)
                return

            if os.path.isdir(fs_path):
                self.list_directory(fs_path)
                return
            if not os.path.isfile(fs_path):
                self.send_error(404)
                return

            size = os.path.getsize(fs_path)
            start, end = 0, size - 1

            range_header = self.headers.get("Range")
            if range_header:
                m = RANGE_RE.match(range_header.strip())
                # Only simple byte ranges are supported; anything else
                # gets the full body (valid per RFC 7233).
                if m and size > 0:
                    if m.group(1):
                        start = int(m.group(1))
                        end = int(m.group(2)) if m.group(2) else size - 1
                    elif m.group(2):  # suffix range: last N bytes
                        start = max(0, size - int(m.group(2)))
                    if start >= size or end < start:
                        self.send_error(416, "Requested Range Not Satisfiable")
                        return
                    end = min(end, size - 1)
                    self.send_response(206)
                    self.send_header("Content-Range", f"bytes {start}-{end}/{size}")
                else:
                    self.send_response(200)
            else:
                self.send_response(200)

            self.send_header("Accept-Ranges", "bytes")
            self.send_header("Content-Type", "application/octet-stream")
            self.send_header("Content-Length", str(end - start + 1))
            self.end_headers()

            if self.command == "HEAD":
                return
            with open(fs_path, "rb") as fh:
                fh.seek(start)
                remaining = end - start + 1
                while remaining > 0:
                    chunk = fh.read(min(1024 * 256, remaining))
                    if not chunk:
                        break
                    self.wfile.write(chunk)
                    remaining -= len(chunk)

        def do_HEAD(self):
            self.do_GET()

        def list_directory(self, dir_path):
            entries = sorted(os.listdir(dir_path))
            rel = os.path.relpath(dir_path, games_dir).replace(os.sep, "/")
            display = "Library root" if rel == "." else rel
            rows = []
            if rel != ".":
                rows.append('<li><a href="../">../</a></li>')
            for name in entries:
                if name.startswith(".") or name.endswith(".part"):
                    continue
                suffix = "/" if os.path.isdir(os.path.join(dir_path, name)) else ""
                rows.append(f'<li><a href="{html.escape(name)}{suffix}">'
                            f'{html.escape(name)}{suffix}</a></li>')
            body = (f"<!DOCTYPE html><html><head><meta charset=\"utf-8\">"
                    f"<title>{html.escape(display)}</title></head><body>"
                    f"<h1>PS Linker — {html.escape(display)}</h1><hr><ul>"
                    + "".join(rows) + "</ul><hr></body></html>").encode()
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def log_message(self, fmt, *args):
            print("[http] %s - %s" % (self.address_string(), fmt % args))

    return PSLinkerHandler


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__, file=sys.stderr)
        return 2
    games_dir = os.path.realpath(sys.argv[1])
    port = int(sys.argv[2]) if len(sys.argv) > 2 else 8000
    httpd = ThreadingHTTPServer(("0.0.0.0", port), make_handler(games_dir))
    print(f"[http] serving {games_dir} on :{port} (Range/resume supported)")
    httpd.serve_forever()


if __name__ == "__main__":
    sys.exit(main())
